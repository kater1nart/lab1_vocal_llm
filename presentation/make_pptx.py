def slide(title, notes):
    s = prs.slides.add_slide(BLANK)
    text(s, 0.6, 0.35, 12.1, 0.9, [title], size=30, bold_first=True)
    SPEECH.append(notes)
    return s


def table(s, x, y, w, rows, col_w=None, size=14):
    t = s.shapes.add_table(len(rows), len(rows[0]), Inches(x), Inches(y), Inches(w), Inches(0.4 * len(rows))).table
    for i, r in enumerate(rows):
        for j, v in enumerate(r):
            c = t.cell(i, j)
            c.text = v
            for p in c.text_frame.paragraphs:
                for run in p.runs:
                    run.font.name = FONT
                    run.font.size = Pt(size)
                    run.font.bold = i == 0
    if col_w:
        for j, cw in enumerate(col_w):
            t.columns[j].width = Inches(cw)
    return t


